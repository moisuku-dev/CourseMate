# ---------------------------------------------------------
# 3. 라벨링 함수 (문자열 매칭 방식으로 변경!)
# ---------------------------------------------------------
def create_label(row):
    # cleaned_content(원본 문장)를 가져옴
    text = str(row['cleaned_content']) 
    
    label_vector = [0] * len(FINAL_TAGS)
    
    for i, tag in enumerate(FINAL_TAGS):
        keywords = TAG_MAPPING[tag]
        for keyword in keywords:
            # 🔥 핵심: 리스트가 아니라 '문장' 안에 키워드가 있는지 확인
            if keyword in text: 
                label_vector[i] = 1
                break 
                
    return label_vector

